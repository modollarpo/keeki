{{--
    Keekii typography pairing.

    Body/UI resolves to var(--be-font-family, var(--font-sans)) in common.css.
    Nothing in this repo imports @fontsource-variable/inter, so Inter is not
    applied from the stylesheet; if the database theme row sets a font_family
    the vendor layout links it from Google Fonts instead.

    Bricolage Grotesque is the display face, reserved for brand moments and
    applied via the `keekii-display` utility in resources/client/keekii-brand.css,
    where the @font-face now lives.

    It was previously pulled from fonts.googleapis.com. That cost a
    render-blocking stylesheet plus DNS and TLS to two third-party origins
    before any heading could paint, and added a third-party origin to the
    critical path of the most visible text on the page. It is now self-hosted
    from /fonts, which is why this section preloads a font file instead of
    linking a stylesheet.

    The preload needs `crossorigin` even though the request is same-origin:
    font fetches are always made in CORS mode, and without the attribute the
    browser would download the file twice -- once for the preload and again for
    the @font-face. `type` is declared so a browser that does not support
    woff2 skips the fetch instead of downloading a file it cannot parse.
--}}
