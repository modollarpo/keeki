    {{--
        PWA installability.

        These were all missing, so the app was not installable: a service worker
        was registered and both the Vite PWA config and resources/client/sw.ts
        precached /manifest.json, but no such file was ever served. The worker
        was precaching a 404.

        Icons are generated by scripts/generate-pwa-icons.ps1 and must not be
        hand-edited -- that script fails if the artwork stops separating from its
        plate.

        The tab favicon is the one surface where the artwork *is* the whole
        background, so it is the one place the light and dark variants genuinely
        differ: a light plate on a dark tab reads as a bright square. Both SVGs
        are offered and the browser picks, via prefers-color-scheme. The PNG
        fallbacks below are unconditioned and therefore always the light plate,
        which is the safer of the two at 16px.

        The 32 and 16 PNGs exist for browsers that do not support SVG favicons.
        apple-touch-icon is required or iOS shows a screenshot of the page; it
        cannot be conditioned, so it is the light plate.

        `theme-color` is the brand orange used as text and controls, which is
        #d84b00 in the theme but resolves to roughly #ce4804 once rounded into
        the OKLCH token. It is a fixed value because a static meta tag cannot
        follow the light/dark theme; this is the light-theme accent.
    --}}
